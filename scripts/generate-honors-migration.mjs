// Generate a staged data import from the reviewed public catalog snapshot.
// This file is outside migrations and is not applied by db push.
import { readFile, writeFile } from 'node:fs/promises'

const catalog = JSON.parse(
  await readFile(new URL('../supabase/catalogs/honors.json', import.meta.url), 'utf8'),
)
const names = new Set()
const quote = (value) => (value === null ? 'null' : `'${value.replaceAll("'", "''")}'`)
for (const honor of catalog.honors) {
  if (names.has(honor.name)) throw new Error(`Duplicate honor: ${honor.name}`)
  names.add(honor.name)
  if (!honor.category || !honor.source_url) throw new Error(`Missing source: ${honor.name}`)
  if (honor.skill_level !== null && ![1, 2, 3].includes(honor.skill_level))
    throw new Error(`Invalid skill level: ${honor.name}`)
  if (honor.year !== null && !Number.isInteger(honor.year))
    throw new Error(`Invalid year: ${honor.name}`)
  const editions = catalog.honors.filter((other) => other.source_name === honor.source_name)
  if (editions.length > 1 && !honor.name.includes(`(${honor.year ?? 'Unknown'})`))
    throw new Error(`Edition must include year: ${honor.name}`)
}
const values = catalog.honors
  .map(
    (h) =>
      `  (${quote(h.name)}, ${quote(h.category)}, ${h.skill_level ?? 'null'}, ${h.year ?? 'null'})`,
  )
  .join(',\n')
const sql = `-- Public NAD and Florida honor catalog, retrieved ${catalog.retrieved_on}.
-- Sources and edition decisions: docs/honors-catalog.md and supabase/catalogs/honors.json.
-- Generated by scripts/generate-honors-migration.mjs; no member data.
begin;

-- Keep existing IDs and all earned-honor references. Unmatched legacy catalog rows remain.
-- Year-qualified editions do not silently reassign an ambiguous legacy honor.
insert into public.honors (name, category, skill_level, year) values
${values}
on conflict (name) do update set
  category = excluded.category,
  skill_level = excluded.skill_level,
  year = excluded.year;

commit;
`
await writeFile(new URL('../supabase/catalogs/import-honors.sql', import.meta.url), sql)
console.log(`Generated ${catalog.honors.length} honors`)
